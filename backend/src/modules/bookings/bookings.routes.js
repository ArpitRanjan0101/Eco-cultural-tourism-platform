'use strict';

const { z } = require('../../core/validation/zod');
const { successEnvelope } = require('../../core/validation/common');
const controller = require('./bookings.controller');
const schema = require('./bookings.schema');
const { partnerGuard } = require('../partners/partners.service');
const { partnerHeaders } = require('../partners/partners.schema');

const TAGS = ['Bookings'];
const ok = (dataSchema, options) => ({ status: 200, schema: successEnvelope(dataSchema, options) });
const list = ok(z.array(schema.bookingSummarySchema), { paginated: true });
const detail = ok(schema.bookingDetailSchema);
const partner = {
  auth: 'user',
  permissions: ['bookings.manage.partner'],
  headers: partnerHeaders,
  middleware: [partnerGuard({})],
  errors: [400, 404],
};

// POST /bookings/:id/payment-order and POST /admin/bookings/:id/refund are delivered with payments (Phase 6).
const routes = [
  {
    method: 'post',
    path: '/bookings/quote',
    tags: TAGS,
    summary: 'Recompute authoritative price and availability',
    description: 'A quote is not a reservation; availability can change before the booking is created.',
    auth: 'user',
    permissions: ['bookings.create.own'],
    rateLimit: { name: 'booking_quote', windowSeconds: 60, max: 60, by: 'user' },
    request: { body: schema.quoteBody },
    response: ok(schema.quoteSchema),
    errors: [404],
    handler: controller.quote,
  },
  {
    method: 'post',
    path: '/bookings',
    tags: TAGS,
    summary: 'Create booking or approval request',
    description:
      'Instant mode holds capacity until the payment deadline (status pending_payment); request mode creates a request ' +
      'the partner approves or rejects (status requested). Requires a verified email and an Idempotency-Key header; ' +
      'replays return the original booking with Idempotent-Replay: true. 409 INSUFFICIENT_AVAILABILITY when capacity is gone.',
    auth: 'user',
    permissions: ['bookings.create.own'],
    rateLimit: { name: 'booking_create', windowSeconds: 600, max: 20, by: 'user' },
    headers: schema.idempotencyHeaders,
    request: { body: schema.createBody },
    response: { status: 201, schema: successEnvelope(schema.bookingDetailSchema) },
    errors: [400, 404, 409],
    handler: controller.create,
  },
  {
    method: 'get',
    path: '/bookings',
    tags: TAGS,
    summary: 'List own bookings',
    auth: 'user',
    permissions: ['bookings.read.own'],
    request: { query: schema.ownListQuery },
    response: list,
    handler: controller.listOwn,
  },
  {
    method: 'get',
    path: '/bookings/:id',
    tags: TAGS,
    summary: 'Get own booking detail',
    auth: 'user',
    permissions: ['bookings.read.own'],
    request: { params: schema.idParams },
    response: detail,
    errors: [404],
    handler: controller.getOwn,
  },
  {
    method: 'get',
    path: '/bookings/:id/status',
    tags: TAGS,
    summary: 'Read current booking/payment state',
    auth: 'user',
    permissions: ['bookings.read.own'],
    request: { params: schema.idParams },
    response: ok(schema.statusSchema),
    errors: [404],
    handler: controller.getStatus,
  },
  {
    method: 'post',
    path: '/bookings/:id/cancel',
    tags: TAGS,
    summary: 'Request/perform cancellation',
    description: 'Unpaid bookings cancel free of charge; paid bookings refund per the policy snapshotted at booking time.',
    auth: 'user',
    permissions: ['bookings.cancel.own'],
    request: { params: schema.idParams, body: schema.cancelBody },
    response: detail,
    errors: [404, 409],
    handler: controller.cancelOwn,
  },
  {
    method: 'get',
    path: '/bookings/:id/documents',
    tags: TAGS,
    summary: 'Retrieve permitted booking documents',
    description: 'Vouchers/receipts with short-lived signed URLs (generated by the worker after confirmation).',
    auth: 'user',
    permissions: ['bookings.read.own'],
    request: { params: schema.idParams },
    response: ok(z.array(schema.documentSchema)),
    errors: [404],
    handler: controller.listDocuments,
  },
  {
    method: 'get',
    path: '/partners/me/bookings',
    tags: ['Partner: Bookings'],
    summary: 'Bookings for partner-owned supply',
    ...partner,
    request: { query: schema.partnerListQuery },
    response: list,
    handler: controller.listForPartner,
  },
  {
    method: 'get',
    path: '/partners/me/bookings/:id',
    tags: ['Partner: Bookings'],
    summary: 'Get partner booking detail',
    ...partner,
    request: { params: schema.idParams },
    response: detail,
    handler: controller.getForPartner,
  },
  {
    method: 'post',
    path: '/partners/me/bookings/:id/approve',
    tags: ['Partner: Bookings'],
    summary: 'Approve request-to-book',
    description: 'Reserves capacity at the quoted price and opens the payment window; 409 if capacity is no longer available.',
    ...partner,
    request: { params: schema.idParams, body: schema.approveBody },
    response: detail,
    errors: [400, 404, 409],
    handler: controller.approve,
  },
  {
    method: 'post',
    path: '/partners/me/bookings/:id/reject',
    tags: ['Partner: Bookings'],
    summary: 'Reject request-to-book',
    ...partner,
    request: { params: schema.idParams, body: schema.rejectBody },
    response: detail,
    errors: [400, 404, 409],
    handler: controller.reject,
  },
  {
    method: 'get',
    path: '/admin/bookings',
    tags: ['Admin: Bookings'],
    summary: 'Search all bookings',
    auth: 'user',
    permissions: ['bookings.read.platform'],
    request: { query: schema.adminListQuery },
    response: list,
    handler: controller.adminList,
  },
  {
    method: 'get',
    path: '/admin/bookings/:id',
    tags: ['Admin: Bookings'],
    summary: 'View full booking',
    auth: 'user',
    permissions: ['bookings.read.platform'],
    request: { params: schema.idParams },
    response: detail,
    errors: [404],
    handler: controller.adminGet,
  },
  {
    method: 'post',
    path: '/admin/bookings/:id/cancel',
    tags: ['Admin: Bookings'],
    summary: 'Authorized cancellation',
    description: 'Audited. waiveFee refunds the full amount regardless of policy; allowed after service start.',
    auth: 'user',
    permissions: ['bookings.manage.platform'],
    request: { params: schema.idParams, body: schema.adminCancelBody },
    response: detail,
    errors: [404, 409],
    handler: controller.adminCancel,
  },
];

module.exports = routes;
