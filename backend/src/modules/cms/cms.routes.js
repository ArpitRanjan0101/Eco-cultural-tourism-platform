'use strict';

const { z } = require('../../core/validation/zod');
const { successEnvelope } = require('../../core/validation/common');
const f = require('../../core/validation/fields');
const controller = require('./cms.controller');
const schema = require('./cms.schema');

const PUBLIC = ['Content'];
const ADMIN = ['Admin: CMS'];
const ok = (dataSchema, options) => ({ status: 200, schema: successEnvelope(dataSchema, options) });
const created = (dataSchema) => ({ status: 201, schema: successEnvelope(dataSchema) });
const noContent = { status: 204, description: 'Done' };
const manage = { auth: 'user', permissions: ['cms.manage'] };

const routes = [
  {
    method: 'get',
    path: '/content/pages/:slug',
    tags: PUBLIC,
    summary: 'Read published public page',
    description: 'Drafts and archived pages return 404. Only enabled, allowlisted sections are serialised.',
    request: { params: f.slugParams },
    response: ok(schema.publicPageSchema),
    errors: [404],
    handler: controller.getPublishedPage,
  },
  {
    method: 'get',
    path: '/content/homepage',
    tags: PUBLIC,
    summary: 'Read approved homepage sections',
    response: ok(schema.publicPageSchema),
    errors: [404],
    handler: controller.getHomepage,
  },
  {
    method: 'get',
    path: '/content/menus/:code',
    tags: PUBLIC,
    summary: 'Read navigation menu',
    request: { params: schema.menuCodeParams },
    response: ok(schema.publicMenuSchema),
    errors: [404],
    handler: controller.getPublicMenu,
  },
  {
    method: 'get',
    path: '/content/announcements',
    tags: PUBLIC,
    summary: 'Read active notices',
    response: ok(z.array(schema.publicAnnouncementSchema)),
    handler: controller.getActiveAnnouncements,
  },

  {
    method: 'get',
    path: '/admin/cms/pages',
    tags: ADMIN,
    summary: 'List all pages',
    ...manage,
    request: { query: schema.pageListQuery },
    response: ok(z.array(schema.pageSchema), { paginated: true }),
    handler: controller.listPages,
  },
  {
    method: 'post',
    path: '/admin/cms/pages',
    tags: ADMIN,
    summary: 'Create page',
    description: 'Created as draft. Only one homepage may exist (409 HOMEPAGE_EXISTS).',
    ...manage,
    request: { body: schema.createPageBody },
    response: created(schema.adminPageSchema),
    errors: [409],
    handler: controller.createPage,
  },
  {
    method: 'get',
    path: '/admin/cms/pages/:id',
    tags: ADMIN,
    summary: 'Read page for editor',
    ...manage,
    request: { params: f.idParams },
    response: ok(schema.adminPageSchema),
    errors: [404],
    handler: controller.getPage,
  },
  {
    method: 'patch',
    path: '/admin/cms/pages/:id',
    tags: ADMIN,
    summary: 'Edit page metadata',
    ...manage,
    request: { params: f.idParams, body: schema.updatePageBody },
    response: ok(schema.adminPageSchema),
    errors: [404, 409],
    handler: controller.updatePage,
  },
  {
    method: 'put',
    path: '/admin/cms/pages/:id/sections',
    tags: ADMIN,
    summary: 'Replace ordered section configuration',
    description:
      'Sections must match the allowlisted registry (hero, rich_text, featured_destinations, category_grid, district_grid, ' +
      'image_gallery, cta_banner, faq). HTML and script URLs are rejected; referenced media/destinations/categories must exist.',
    ...manage,
    request: { params: f.idParams, body: schema.sectionsBody },
    response: ok(schema.adminPageSchema),
    errors: [404],
    handler: controller.replaceSections,
  },
  {
    method: 'patch',
    path: '/admin/cms/pages/:id/status',
    tags: ADMIN,
    summary: 'Draft/publish/archive',
    auth: 'user',
    permissions: ['cms.publish'],
    request: { params: f.idParams, body: f.statusBody(f.publishStatus) },
    response: ok(schema.adminPageSchema),
    errors: [404],
    handler: controller.setPageStatus,
  },
  {
    method: 'delete',
    path: '/admin/cms/pages/:id',
    tags: ADMIN,
    summary: 'Archive page',
    auth: 'user',
    permissions: ['cms.publish'],
    request: { params: f.idParams },
    response: noContent,
    errors: [404],
    handler: controller.archivePage,
  },
  { method: 'get', path: '/admin/cms/menus', tags: ADMIN, summary: 'Manage menus', ...manage, response: ok(z.array(schema.adminMenuSchema)), handler: controller.listMenus },
  {
    method: 'post',
    path: '/admin/cms/menus',
    tags: ADMIN,
    summary: 'Create menu',
    ...manage,
    request: { body: schema.createMenuBody },
    response: created(schema.adminMenuSchema),
    errors: [409],
    handler: controller.createMenu,
  },
  {
    method: 'put',
    path: '/admin/cms/menus/:id/items',
    tags: ADMIN,
    summary: 'Replace ordered menu tree',
    description: 'Max depth 3 and 100 items. linkValue is validated per linkType (path, https URL or slug).',
    ...manage,
    request: { params: f.idParams, body: schema.menuItemsBody },
    response: ok(schema.adminMenuSchema),
    errors: [404],
    handler: controller.replaceMenuItems,
  },
  { method: 'get', path: '/admin/cms/redirects', tags: ADMIN, summary: 'Read redirects', ...manage, response: ok(z.array(schema.redirectSchema)), handler: controller.listRedirects },
  {
    method: 'post',
    path: '/admin/cms/redirects',
    tags: ADMIN,
    summary: 'Create redirect',
    ...manage,
    request: { body: schema.createRedirectBody },
    response: created(schema.redirectSchema),
    errors: [409],
    handler: controller.createRedirect,
  },
  {
    method: 'delete',
    path: '/admin/cms/redirects/:id',
    tags: ADMIN,
    summary: 'Delete redirect',
    ...manage,
    request: { params: f.idParams },
    response: noContent,
    errors: [404],
    handler: controller.deleteRedirect,
  },
  {
    method: 'get',
    path: '/admin/cms/announcements',
    tags: ADMIN,
    summary: 'Read announcements',
    ...manage,
    request: { query: schema.announcementListQuery },
    response: ok(z.array(schema.announcementSchema)),
    handler: controller.listAnnouncements,
  },
  {
    method: 'post',
    path: '/admin/cms/announcements',
    tags: ADMIN,
    summary: 'Create announcement',
    ...manage,
    request: { body: schema.createAnnouncementBody },
    response: created(schema.announcementSchema),
    handler: controller.createAnnouncement,
  },
  {
    method: 'patch',
    path: '/admin/cms/announcements/:id',
    tags: ADMIN,
    summary: 'Edit announcement',
    ...manage,
    request: { params: f.idParams, body: schema.updateAnnouncementBody },
    response: ok(schema.announcementSchema),
    errors: [404],
    handler: controller.updateAnnouncement,
  },
  {
    method: 'delete',
    path: '/admin/cms/announcements/:id',
    tags: ADMIN,
    summary: 'Remove announcement',
    ...manage,
    request: { params: f.idParams },
    response: noContent,
    errors: [404],
    handler: controller.deleteAnnouncement,
  },
];

module.exports = routes;
