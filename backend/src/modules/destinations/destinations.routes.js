'use strict';

const { z } = require('../../core/validation/zod');
const { successEnvelope } = require('../../core/validation/common');
const f = require('../../core/validation/fields');
const controller = require('./destinations.controller');
const schema = require('./destinations.schema');

const PUBLIC = ['Destinations'];
const ADMIN = ['Admin: Destinations'];
const ok = (dataSchema, options) => ({ status: 200, schema: successEnvelope(dataSchema, options) });
const created = (dataSchema) => ({ status: 201, schema: successEnvelope(dataSchema) });
const noContent = { status: 204, description: 'Done' };
const cards = ok(z.array(schema.destinationCardSchema), { paginated: true });
const detail = ok(schema.destinationDetailSchema);
const read = { auth: 'user', permissions: ['destinations.read'] };
const manage = { auth: 'user', permissions: ['destinations.manage'] };
const geography = { auth: 'user', permissions: ['geography.manage'] };

// Static paths are registered before parameterised ones (e.g. /destinations/featured before /:slug).
// Served by the modules that own the data: /destinations/:slug/experiences, /properties, /guides (supply modules)
// and /destinations/:slug/reviews (reviews module).
const routes = [
  {
    method: 'get',
    path: '/districts/:slug/destinations',
    tags: PUBLIC,
    summary: 'List district attractions',
    request: { params: f.slugParams, query: schema.districtDestinationsQuery },
    response: cards,
    errors: [404],
    handler: controller.listByDistrict,
  },
  {
    method: 'get',
    path: '/destination-categories',
    tags: PUBLIC,
    summary: 'List destination categories',
    response: ok(z.array(schema.categorySchema)),
    handler: controller.listPublicCategories,
  },
  {
    method: 'get',
    path: '/destinations',
    tags: PUBLIC,
    summary: 'List/filter published destinations',
    request: { query: schema.publicListQuery },
    response: cards,
    errors: [404],
    handler: controller.listPublic,
  },
  {
    method: 'get',
    path: '/destinations/featured',
    tags: PUBLIC,
    summary: 'Get featured destinations',
    request: { query: schema.featuredQuery },
    response: ok(z.array(schema.destinationCardSchema)),
    handler: controller.listFeatured,
  },
  {
    method: 'get',
    path: '/destinations/:slug',
    tags: PUBLIC,
    summary: 'Get destination detail',
    request: { params: f.slugParams },
    response: detail,
    errors: [404],
    handler: controller.getPublic,
  },
  {
    method: 'get',
    path: '/destinations/:slug/nearby',
    tags: PUBLIC,
    summary: 'Get nearby destinations',
    description: 'Published destinations within radiusKm (PostGIS), nearest first, with distanceKm.',
    request: { params: f.slugParams, query: schema.nearbyQuery },
    response: cards,
    errors: [404],
    handler: controller.nearby,
  },

  {
    method: 'get',
    path: '/admin/destinations',
    tags: ADMIN,
    summary: 'List destinations including drafts',
    ...read,
    request: { query: schema.adminListQuery },
    response: cards,
    handler: controller.adminList,
  },
  {
    method: 'post',
    path: '/admin/destinations',
    tags: ADMIN,
    summary: 'Create destination',
    description: 'Created as draft. Slug defaults to a slugified name.',
    ...manage,
    request: { body: schema.createBody },
    response: created(schema.destinationDetailSchema),
    errors: [409],
    handler: controller.create,
  },
  {
    method: 'get',
    path: '/admin/destinations/:id',
    tags: ADMIN,
    summary: 'Read admin destination detail',
    ...read,
    request: { params: f.idParams },
    response: detail,
    errors: [404],
    handler: controller.adminGet,
  },
  {
    method: 'patch',
    path: '/admin/destinations/:id',
    tags: ADMIN,
    summary: 'Update destination',
    ...manage,
    request: { params: f.idParams, body: schema.updateBody },
    response: detail,
    errors: [404, 409],
    handler: controller.update,
  },
  {
    method: 'patch',
    path: '/admin/destinations/:id/status',
    tags: ADMIN,
    summary: 'Publish/unpublish destination',
    description: 'Publishing requires summary, description, location and at least one category (422 PUBLISH_REQUIREMENTS).',
    auth: 'user',
    permissions: ['destinations.publish'],
    request: { params: f.idParams, body: schema.statusBody },
    response: detail,
    errors: [404],
    handler: controller.setStatus,
  },
  {
    method: 'delete',
    path: '/admin/destinations/:id',
    tags: ADMIN,
    summary: 'Archive destination',
    description: 'Soft archive; linked bookings, reviews and audit history stay consistent.',
    ...manage,
    request: { params: f.idParams },
    response: noContent,
    errors: [404],
    handler: controller.archive,
  },
  {
    method: 'put',
    path: '/admin/destinations/:id/categories',
    tags: ADMIN,
    summary: 'Replace destination categories',
    ...manage,
    request: { params: f.idParams, body: schema.categoriesBody },
    response: detail,
    errors: [404],
    handler: controller.setCategories,
  },
  {
    method: 'post',
    path: '/admin/destinations/:id/media',
    tags: ADMIN,
    summary: 'Attach destination media',
    description: 'Media must be a completed content_image upload. isCover replaces the current cover.',
    ...manage,
    request: { params: f.idParams, body: schema.attachMediaBody },
    response: detail,
    errors: [404],
    handler: controller.attachMedia,
  },
  {
    method: 'delete',
    path: '/admin/destinations/:id/media/:mediaId',
    tags: ADMIN,
    summary: 'Detach media',
    ...manage,
    request: { params: schema.mediaParams },
    response: noContent,
    errors: [404],
    handler: controller.detachMedia,
  },
  {
    method: 'put',
    path: '/admin/destinations/:id/faqs',
    tags: ADMIN,
    summary: 'Replace FAQs',
    ...manage,
    request: { params: f.idParams, body: schema.faqsBody },
    response: detail,
    errors: [404],
    handler: controller.replaceFaqs,
  },
  {
    method: 'put',
    path: '/admin/destinations/:id/related',
    tags: ADMIN,
    summary: 'Set related destinations',
    ...manage,
    request: { params: f.idParams, body: schema.relatedBody },
    response: detail,
    errors: [404],
    handler: controller.setRelated,
  },
  {
    method: 'get',
    path: '/admin/destination-categories',
    tags: ADMIN,
    summary: 'List managed categories',
    ...geography,
    request: { query: schema.categoryListQuery },
    response: ok(z.array(schema.categorySchema)),
    handler: controller.listCategories,
  },
  {
    method: 'post',
    path: '/admin/destination-categories',
    tags: ADMIN,
    summary: 'Create category',
    ...geography,
    request: { body: schema.createCategoryBody },
    response: created(schema.categorySchema),
    errors: [409],
    handler: controller.createCategory,
  },
  {
    method: 'patch',
    path: '/admin/destination-categories/:id',
    tags: ADMIN,
    summary: 'Update category',
    ...geography,
    request: { params: f.idParams, body: schema.updateCategoryBody },
    response: ok(schema.categorySchema),
    errors: [404, 409],
    handler: controller.updateCategory,
  },
  {
    method: 'patch',
    path: '/admin/destination-categories/:id/status',
    tags: ADMIN,
    summary: 'Set category status',
    ...geography,
    request: { params: f.idParams, body: f.statusBody(f.activeStatus) },
    response: ok(schema.categorySchema),
    errors: [404],
    handler: controller.setCategoryStatus,
  },
];

module.exports = routes;
