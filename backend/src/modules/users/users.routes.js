'use strict';

const { z } = require('../../core/validation/zod');
const { successEnvelope } = require('../../core/validation/common');
const controller = require('./users.controller');
const schema = require('./users.schema');

const ok = (dataSchema, options) => ({ status: 200, schema: successEnvelope(dataSchema, options) });

const routes = [
  {
    method: 'get',
    path: '/users/me',
    tags: ['Users'],
    summary: 'Read personal profile',
    auth: 'user',
    response: ok(schema.userSchema),
    handler: controller.getMe,
  },
  {
    method: 'patch',
    path: '/users/me',
    tags: ['Users'],
    summary: 'Update personal profile',
    description: 'Changing the phone number clears its verification.',
    auth: 'user',
    request: { body: schema.updateMeBody },
    response: ok(schema.userSchema),
    errors: [409],
    handler: controller.updateMe,
  },
  {
    method: 'get',
    path: '/users/me/roles',
    tags: ['Users'],
    summary: 'Read assigned roles',
    auth: 'user',
    response: ok(z.array(schema.roleSchema)),
    handler: controller.getMyRoles,
  },
  {
    method: 'get',
    path: '/admin/users',
    tags: ['Admin: Users & RBAC'],
    summary: 'Search user accounts',
    auth: 'user',
    permissions: ['users.read'],
    request: { query: schema.adminUserListQuery },
    response: ok(z.array(schema.userSummarySchema), { paginated: true }),
    handler: controller.searchUsers,
  },
  {
    method: 'get',
    path: '/admin/users/:id',
    tags: ['Admin: Users & RBAC'],
    summary: 'Read user account',
    auth: 'user',
    permissions: ['users.read'],
    request: { params: schema.idParams },
    response: ok(schema.userSchema),
    errors: [404],
    handler: controller.getUser,
  },
  {
    method: 'patch',
    path: '/admin/users/:id/status',
    tags: ['Admin: Users & RBAC'],
    summary: 'Suspend or reactivate user',
    description: 'Suspension revokes all sessions immediately. Audited. Administrators can only be changed by a super admin.',
    auth: 'user',
    permissions: ['users.manage'],
    request: { params: schema.idParams, body: schema.setStatusBody },
    response: ok(schema.userSchema),
    errors: [404],
    handler: controller.setUserStatus,
  },
  {
    method: 'put',
    path: '/admin/users/:id/roles',
    tags: ['Admin: Users & RBAC'],
    summary: 'Set user roles',
    description: 'Replaces the role set. Audited. Granting/revoking admin roles requires super admin; self-changes are refused.',
    auth: 'user',
    permissions: ['roles.assign'],
    request: { params: schema.idParams, body: schema.setRolesBody },
    response: ok(schema.userSchema),
    errors: [404],
    handler: controller.setUserRoles,
  },
  {
    method: 'get',
    path: '/admin/roles',
    tags: ['Admin: Users & RBAC'],
    summary: 'List roles',
    auth: 'user',
    permissions: ['roles.read'],
    response: ok(z.array(schema.roleWithPermissionsSchema)),
    handler: controller.listRoles,
  },
  {
    method: 'get',
    path: '/admin/permissions',
    tags: ['Admin: Users & RBAC'],
    summary: 'List permissions',
    auth: 'user',
    permissions: ['roles.read'],
    response: ok(z.array(schema.permissionSchema)),
    handler: controller.listPermissions,
  },
  {
    method: 'put',
    path: '/admin/roles/:id/permissions',
    tags: ['Admin: Users & RBAC'],
    summary: 'Set permissions for role',
    description: 'Replaces the permission set. Audited. The super_admin role is immutable (409).',
    auth: 'user',
    permissions: ['roles.manage'],
    request: { params: schema.idParams, body: schema.setRolePermissionsBody },
    response: ok(schema.roleWithPermissionsSchema),
    errors: [404, 409],
    handler: controller.setRolePermissions,
  },
];

module.exports = routes;
